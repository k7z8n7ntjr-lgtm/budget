"""Build the PWA from src/app.html into the repository root (served by GitHub Pages).

    python3 build.py

Bump VERSION on every release: phones only pick up new files when the service worker cache name changes.
"""
import json, pathlib, re
from PIL import Image, ImageDraw

VERSION = 'v17'
ROOT = pathlib.Path(__file__).parent
app = (ROOT / 'src/app.html').read_text()

head = '''<!doctype html>
<html lang="ru" class="pwa">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#F3F4F1">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<meta name="apple-mobile-web-app-title" content="Бюджет">
<link rel="manifest" href="manifest.json">
<link rel="apple-touch-icon" href="icon-180.png">
<link rel="icon" href="icon-192.png">
<style>html,body{margin:0}body{-webkit-text-size-adjust:100%}</style>
'''
# src/app.html is a page fragment (<title>, <style>, markup, <script>); wrap it into a full document
split = re.search(r'</style>', app).end()
(ROOT / 'index.html').write_text(head + app[:split] + '\n</head>\n<body>\n' + app[split:] + '\n</body>\n</html>\n')

(ROOT / 'manifest.json').write_text(json.dumps({
    "name": "Месячный бюджет", "short_name": "Бюджет", "lang": "ru", "start_url": "./", "scope": "./",
    "display": "standalone", "background_color": "#F3F4F1", "theme_color": "#F3F4F1",
    "icons": [{"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
              {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"}]},
    ensure_ascii=False, indent=1))

(ROOT / 'sw.js').write_text(f'''// Generated by build.py. VERSION changes on every release so phones pick up the new files.
const VERSION = '{VERSION}';
const FILES = ['./', './index.html', './manifest.json', './icon-180.png', './icon-192.png', './icon-512.png'];
self.addEventListener('install', (e) => {{ e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES))); self.skipWaiting(); }});
self.addEventListener('activate', (e) => {{ e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== VERSION).map((k) => caches.delete(k))))); self.clients.claim(); }});
// Network first (so updates arrive), cache as offline fallback.
self.addEventListener('fetch', (e) => {{
  if (e.request.method !== 'GET') return;
  e.respondWith(fetch(e.request).then((r) => {{ const copy = r.clone(); caches.open(VERSION).then((c) => c.put(e.request, copy)); return r; }})
    .catch(() => caches.match(e.request, {{ ignoreSearch: true }}).then((r) => r || caches.match('./index.html'))));
}});
''')

def icon(n):
    s = n * 4; im = Image.new('RGB', (s, s), '#24584A'); d = ImageDraw.Draw(im)
    cx = s / 2; R = s * 0.30; w = s * 0.055
    d.ellipse([cx - R, cx - R, cx + R, cx + R], outline='#3E7A69', width=int(w))
    d.arc([cx - R, cx - R, cx + R, cx + R], start=-90, end=150, fill='#FFFFFF', width=int(w))
    x0 = cx - s * 0.07; y0 = cx - s * 0.13; lw = int(s * 0.035)
    d.line([x0, y0, x0, cx + s * 0.14], fill='white', width=lw)
    d.arc([x0 - s * 0.09, y0, x0 + s * 0.11, cx + s * 0.03], start=-90, end=90, fill='white', width=lw)
    d.line([x0, y0 + lw / 2, x0 + s * 0.01, y0 + lw / 2], fill='white', width=lw)
    d.line([x0 - s * 0.06, cx + s * 0.08, x0 + s * 0.07, cx + s * 0.08], fill='white', width=lw)
    return im.resize((n, n), Image.LANCZOS)

for n in (180, 192, 512):
    p = ROOT / f'icon-{n}.png'
    if not p.exists():
        icon(n).save(p)
print('built', VERSION)
